#!/usr/bin/env node
/**
 * Writes .env.production from wrangler.jsonc vars before `vite build`.
 *
 * PUBLIC_CONVEX_URL and PUBLIC_CONVEX_SITE_URL are imported via `$env/static/public`
 * (in src/routes/+layout.svelte and @mmailaender/convex-better-auth-svelte), so Vite
 * inlines them at build time. Runtime-only Worker var overrides cannot replace them.
 *
 * Target selection:
 * - Preview (`previews.vars` → dev Convex `fastidious-setter-628`):
 *   - `--preview` CLI flag or `BUILD_TARGET=preview` / `CONVEX_PREVIEW=1`
 *   - Cloudflare Workers Builds / Pages non-production branches
 *     (`WORKERS_CI_BRANCH` or `CF_PAGES_BRANCH` set and !== `PRODUCTION_BRANCH` / `main`)
 * - Production (`vars` → prod Convex `agreeable-grouse-769`):
 *   - Default when on `main` or running `npm run build` locally without `--preview`,
 *     or when `--prod` / `BUILD_TARGET=production` is passed.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

export const BUILD_KEYS = [
  "PUBLIC_CONVEX_URL",
  "PUBLIC_CONVEX_SITE_URL",
  "PUBLIC_SITE_URL",
  "PUBLIC_APP_URL",
  "USE_CONVEX",
];

/** @param {string} text */
export function parseJsonc(text) {
  const stripped = text
    .split("\n")
    .filter((line) => !line.trimStart().startsWith("//"))
    .join("\n");
  return JSON.parse(stripped);
}

/**
 * Determines whether the current build targets a non-production preview deployment.
 *
 * @param {{ argv?: string[]; env?: Record<string, string | undefined> }} [options]
 */
export function isPreviewBuild(options = {}) {
  const argv = options.argv ?? process.argv.slice(2);
  const env = options.env ?? process.env;

  if (argv.includes("--prod") || env.BUILD_TARGET === "production") {
    return false;
  }
  if (
    argv.includes("--preview") ||
    env.BUILD_TARGET === "preview" ||
    env.CONVEX_PREVIEW === "1" ||
    env.CONVEX_PREVIEW === "true"
  ) {
    return true;
  }

  const productionBranch = (env.PRODUCTION_BRANCH || "main").trim();
  const ciBranch = (env.WORKERS_CI_BRANCH || env.CF_PAGES_BRANCH || "").trim();
  if (ciBranch && ciBranch !== productionBranch) {
    return true;
  }

  return false;
}

/**
 * Resolves the build-time variables from parsed `wrangler.jsonc`.
 *
 * @param {Record<string, any>} config
 * @param {{ preview?: boolean }} [options]
 * @returns {{ selected: Record<string, string>; missing: string[] }}
 */
export function resolveBuildVars(config, options = {}) {
  const baseVars = config.vars ?? {};
  const previewVars = options.preview ? (config.previews?.vars ?? {}) : {};
  const merged = { ...baseVars, ...previewVars };

  /** @type {Record<string, string>} */
  const selected = {};
  /** @type {string[]} */
  const missing = [];

  for (const key of BUILD_KEYS) {
    const value = merged[key];
    if (value !== undefined && value !== "") {
      selected[key] = String(value);
    } else if (
      key === "PUBLIC_CONVEX_URL" ||
      key === "PUBLIC_CONVEX_SITE_URL" ||
      key === "USE_CONVEX"
    ) {
      missing.push(key);
    }
  }

  return { selected, missing };
}

/**
 * Formats the `.env.production` file contents.
 *
 * @param {Record<string, string>} selected
 * @param {string} sourceLabel
 */
export function formatEnvProduction(selected, sourceLabel) {
  const lines = [
    "# Auto-generated by scripts/sync-wrangler-build-env.mjs — do not edit",
    `# Source: ${sourceLabel}`,
    "",
  ];
  for (const [key, value] of Object.entries(selected)) {
    lines.push(`${key}=${value}`);
  }
  return `${lines.join("\n")}\n`;
}

function main() {
  const root = process.cwd();
  const wranglerPath = resolve(root, "wrangler.jsonc");
  const outPath = resolve(root, ".env.production");

  const config = parseJsonc(readFileSync(wranglerPath, "utf8"));
  const preview = isPreviewBuild();
  const sourceLabel = preview
    ? "wrangler.jsonc previews.vars (preview)"
    : "wrangler.jsonc vars (production)";
  const { selected, missing } = resolveBuildVars(config, { preview });

  if (missing.length > 0) {
    console.error(
      `Missing required ${sourceLabel} keys for build: ${missing.join(", ")}`,
    );
    process.exit(1);
  }

  writeFileSync(outPath, formatEnvProduction(selected, sourceLabel));
  const writtenKeys = Object.keys(selected);
  console.log(
    `Wrote ${outPath} from ${sourceLabel} (${writtenKeys.length} vars, PUBLIC_CONVEX_URL=${selected.PUBLIC_CONVEX_URL})`,
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  main();
}
