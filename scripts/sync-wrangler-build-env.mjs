#!/usr/bin/env node
/**
 * Writes .env.production from wrangler.jsonc vars before `vite build`.
 * Cloudflare Pages CI has no gitignored .env.production.local; wrangler.jsonc
 * vars only apply at Worker runtime, not during the build step.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();
const wranglerPath = resolve(root, "wrangler.jsonc");
const outPath = resolve(root, ".env.production");

/** @param {string} text */
function parseJsonc(text) {
  const stripped = text
    .split("\n")
    .filter((line) => !line.trimStart().startsWith("//"))
    .join("\n");
  return JSON.parse(stripped);
}

const BUILD_KEYS = [
  "PUBLIC_CONVEX_URL",
  "PUBLIC_CONVEX_SITE_URL",
  "PUBLIC_SITE_URL",
  "PUBLIC_APP_URL",
  "USE_CONVEX",
];

const config = parseJsonc(readFileSync(wranglerPath, "utf8"));
const vars = config.vars ?? {};

const lines = [
  "# Auto-generated by scripts/sync-wrangler-build-env.mjs — do not edit",
  "# Source: wrangler.jsonc vars",
  "",
];

const written = [];
const missing = [];

for (const key of BUILD_KEYS) {
  const value = vars[key];
  if (value !== undefined && value !== "") {
    lines.push(`${key}=${value}`);
    written.push(key);
  } else if (
    key === "PUBLIC_CONVEX_URL" ||
    key === "PUBLIC_CONVEX_SITE_URL" ||
    key === "USE_CONVEX"
  ) {
    missing.push(key);
  }
}

if (missing.length > 0) {
  console.error(
    `Missing required wrangler.jsonc vars for build: ${missing.join(", ")}`,
  );
  process.exit(1);
}

writeFileSync(outPath, `${lines.join("\n")}\n`);
console.log(`Wrote ${outPath} from wrangler.jsonc (${written.length} vars)`);
